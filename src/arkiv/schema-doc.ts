// Renders arkiv/schema.md from the kind definitions (B1.2-R5): the generated document is the
// source of truth readers and the Arkiv prize's `/arkiv/schema.md` requirement point at, and a
// test fails when the committed file is stale. Run `pnpm arkiv:schema` after changing kinds.ts.
import { commonColumns, KIND_NAMES, KINDS } from "./kinds";

type Col = { type: string; isIndexed: boolean; isOptional: boolean };

const flagText = (f: { readonly: boolean; permissionlessExtension?: boolean }) =>
  [f.readonly ? "readonly" : "mutable", f.permissionlessExtension ? "permissionlessExtension" : null]
    .filter(Boolean)
    .join(" + ");

export function renderSchemaMarkdown(): string {
  const out: string[] = [];
  out.push(
    "# Arkiv schema",
    "",
    "<!-- Generated by `pnpm arkiv:schema` from src/arkiv/kinds.ts. Do not edit by hand. -->",
    "",
    "Lanyard stores everything people do as Arkiv entities on **Rabdi** (chain `7794095`). Every",
    "record is written by the actor's own wallet, carries the four common indexed attributes below,",
    "and is untagged (no `arkiv.schema` attribute): readers filter on `app`, `event` and `kind`.",
    "Owners can patch only mutable records; readonly records can still be deleted or transferred by",
    "their owner, so the freeze operator retains captured evidence. Retention is physical expiry,",
    "never a business deadline.",
    "",
    "## Common attributes",
    "",
    "| Attribute | Type | Indexed | Meaning |",
    "| --- | --- | --- | --- |",
    "| `app` | str | yes | Always `lanyard` |",
    "| `event` | str | yes | The edition, e.g. `mumbai2026` |",
    "| `kind` | str | yes | One of the kinds below |",
    "| `by_label` | str | yes | The writer's relative ENS label (`priya.volunteers`) or authority persona (`organizer`); Arkiv reserves `by` |",
    "",
    "## Kinds",
    "",
    "| Kind | Written by | Flags | Retention | Meaning |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const name of KIND_NAMES) {
    const k = KINDS[name];
    out.push(`| \`${name}\` | ${k.writer} | ${flagText(k.flags)} | ${k.retention.describe} | ${k.about} |`);
  }
  out.push("", "## Columns per kind", "");
  const common = new Set(Object.keys(commonColumns));
  for (const name of KIND_NAMES) {
    const cols = Object.entries(KINDS[name].schema.columns as Record<string, Col>).filter(
      ([c]) => !common.has(c),
    );
    out.push(`### \`${name}\``, "", "| Column | Type | Indexed | Optional |", "| --- | --- | --- | --- |");
    for (const [c, col] of cols)
      out.push(
        `| \`${c}\` | ${col.type} | ${col.isIndexed ? "yes" : "no"} | ${col.isOptional ? "yes" : "no"} |`,
      );
    out.push("");
  }
  out.push(
    "## Querying",
    "",
    "Queries are current-state equality filters on indexed columns, ordered by key, at most 100 rows",
    "per page; the node rejects `!=`, so status is modeled positively (e.g. a ticket is closed by a",
    "`ticket_resolution`, never by filtering `status != open`). Example: every help ticket of the",
    "edition, with the pinned SDK:",
    "",
    "```ts",
    'import { createPublicClient } from "@arkiv-network/sdk";',
    'import { rabdi } from "@arkiv-network/sdk/chains";',
    'import { and, asc, eq } from "@arkiv-network/sdk/query";',
    'import { http } from "viem";',
    "",
    'const client = createPublicClient({ chain: rabdi({ accessKey: "" }), transport: http() });',
    "const page = await client",
    "  .select({ $key: true, $creator: true, $createdAt: true, $attributes: true })",
    '  .where(and(eq("app", "lanyard"), eq("event", "mumbai2026"), eq("kind", "ticket")))',
    '  .orderBy(asc("$key"))',
    "  .limit(100)",
    "  .fetch();",
    "```",
    "",
  );
  return out.join("\n");
}
