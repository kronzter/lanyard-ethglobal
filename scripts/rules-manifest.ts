// The RULES_VERSION manifest (B2.3-R1; plans/01-evidence-and-interfaces.md §2), read from disk.
//
// esbuild resolves `src/rules/index.ts` exactly as a bundler would and reports every input file.
// Repo sources (the rules plus every transitive shared/arkiv helper) enter as repo-relative paths
// with the keccak256 of their LF-normalized bytes; files under node_modules enter as the resolved
// package name and exact version. The generated version file itself is excluded, so writing it
// never changes the hash. No absolute paths, timestamps or build output appear.
import { readFileSync } from "node:fs";
import path from "node:path";
import { build } from "esbuild";
import {
  RulesManifestSchema,
  sourceFileHash,
  type RulesManifest,
} from "../src/shared/evidence/rules-version";

export const ROOT = path.resolve(import.meta.dirname, "..");
export const RULES_ENTRY = "src/rules/index.ts";
export const VERSION_FILE = "src/rules/version.generated.ts";

/** The nearest package.json above `file` that names a package and its version. */
function packageOf(file: string): { name: string; version: string } {
  let dir = path.dirname(file);
  for (;;) {
    try {
      const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8")) as {
        name?: string;
        version?: string;
      };
      if (pkg.name && pkg.version) return { name: pkg.name, version: pkg.version };
    } catch {
      // no package.json here; keep walking up
    }
    const up = path.dirname(dir);
    if (up === dir) throw new Error(`no package.json with name and version above ${file}`);
    dir = up;
  }
}

export async function rulesManifest(root = ROOT): Promise<RulesManifest> {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [RULES_ENTRY],
    bundle: true,
    write: false,
    metafile: true,
    platform: "browser",
    format: "esm",
    logLevel: "silent",
  });
  const files: RulesManifest["files"] = [];
  const deps = new Map<string, { name: string; version: string }>();
  for (const input of Object.keys(result.metafile.inputs)) {
    const rel = input.split(path.sep).join("/");
    if (rel.includes("node_modules/")) {
      const pkg = packageOf(path.resolve(root, input));
      deps.set(`${pkg.name}@${pkg.version}`, pkg);
    } else if (rel !== VERSION_FILE) {
      files.push({ path: rel, hash: sourceFileHash(readFileSync(path.resolve(root, input), "utf8")) });
    }
  }
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const dependencies = [...deps.values()].sort((a, b) =>
    a.name !== b.name
      ? a.name < b.name
        ? -1
        : 1
      : a.version < b.version
        ? -1
        : a.version > b.version
          ? 1
          : 0,
  );
  return RulesManifestSchema.parse({ schemaVersion: 1, files, dependencies });
}

export const versionFileText = (version: string) =>
  `// Generated by \`pnpm rules:version\` from the rules source manifest (B2.3-R1); do not edit.\n` +
  `// A staleness test fails when it is out of date.\n` +
  `export const RULES_VERSION = "${version}" as const;\n`;
